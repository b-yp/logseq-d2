import { build, context } from 'esbuild'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const indexPath = join(root, 'index.html')
const pkgPath = join(root, 'package.json')
const buildInfoPath = join(root, 'src', 'build-info.ts')
const watch = process.argv.includes('--watch')

const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'))

function getFormattedTime() {
  const now = new Date()
  const pad = (n) => String(n).padStart(2, '0')
  return `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())} ${pad(now.getHours())}:${pad(now.getMinutes())}:${pad(now.getSeconds())}`
}

function updateBuildInfo() {
  const buildTime = getFormattedTime()
  const content = `// This file is auto-generated by scripts/build.mjs\nexport const BUILD_TIME = '${buildTime}'\nexport const BUILD_VERSION = '${pkg.version}'\n`
  writeFileSync(buildInfoPath, content, 'utf8')
  return buildTime
}

function bumpCacheBust(buildTime) {
  const stamp = Date.now().toString(36)
  const html = readFileSync(indexPath, 'utf8')
  const next = html.replace(
    /index\.js\?v=[^"']*/,
    `index.js?v=${stamp}`,
  )
  if (next !== html) writeFileSync(indexPath, next)
  console.log(`[build] ${buildTime} - index.html cache-bust v=${stamp} (v${pkg.version})`)
}

const options = {
  absWorkingDir: root,
  entryPoints: ['src/main.ts'],
  bundle: true,
  outfile: 'dist/index.js',
  format: 'iife',
  target: 'es2020',
  define: { global: 'globalThis' },
  logLevel: 'info',
}

mkdirSync(join(root, 'dist'), { recursive: true })

let currentBuildTime = updateBuildInfo()

const buildPlugin = {
  name: 'logseq-d2-build-meta',
  setup(buildCtx) {
    buildCtx.onStart(() => {
      currentBuildTime = updateBuildInfo()
    })
    buildCtx.onEnd((result) => {
      if (result.errors.length === 0) {
        bumpCacheBust(currentBuildTime)
      }
    })
  },
}

if (watch) {
  const ctx = await context({
    ...options,
    plugins: [buildPlugin],
  })
  await ctx.watch()
  console.log('[build] watching for changes...')
} else {
  await build({
    ...options,
    plugins: [buildPlugin],
  })
}
